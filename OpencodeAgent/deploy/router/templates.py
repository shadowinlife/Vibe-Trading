def render_fleet(out_dir: Path, tenant_ids: Iterable[str]) -> str:
    """Render the fleet compose that ``include``s every tenant's own file."""
    includes = "\n".join(
        f"  - path: {out_dir / tenant_id / COMPOSE_FILENAME}"
        for tenant_id in sorted(tenant_ids)
    )
    return f"# Generated by provision_tenant.py\nname: vt-tenant-fleet\ninclude:\n{includes}\n"


def read_dotenv(path: Path | None) -> dict[str, str]:
    """Parse a flat KEY=VALUE dotenv file (no shell semantics, no interpolation)."""
    if path is None or not path.exists():
        return {}
    values: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, _, value = stripped.partition("=")
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values
