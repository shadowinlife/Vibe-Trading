def render_json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def build_outputs() -> dict[Path, str]:
    corpus = load_jsonl(CORPUS_PATH)
    rows, agreement = classify_twice(corpus)
    intake = build_intake(corpus, load_runs(RUN_PATH))
    dist = build_distribution(corpus, rows, agreement, json.loads(REAL_PATH.read_text(encoding="utf-8")))
    return {INTAKE_PATH: render_json(intake), DIST_PATH: render_json(dist), VERDICT_PATH: build_verdict(intake, dist)}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify published files match recomputation")
    args = parser.parse_args(argv)
    outputs = build_outputs()
    if not args.check:
        for path, text in outputs.items():
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path}")
        return 0
    drift = [str(path) for path, text in outputs.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
    if drift:
        print("[drift] " + ", ".join(drift), file=sys.stderr)
        return 1
    print("[ok] intake_load_rate.json, request_distribution.json and wave0_verdict.md match recomputation")
    return 0


