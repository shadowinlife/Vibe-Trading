"""Render ``ab_report.md`` from the analysis produced by ``ab_analysis.py``.

The renderer is deterministic: every number, digest and cross-reference comes
from committed files. It never runs a model and never decides the experiment;
the verdict is the pre-registered rule's output.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Iterable

BASE_DIR = Path(__file__).resolve().parent
REPO_ROOT = BASE_DIR.parents[4]
PILOT_NOTES = {
    (
        "c02",
        "experiment",
    ): "wave1_frozen10_report.md: no artifact (600 s cap); proxy still counts success",
    (
        "c05",
        "experiment",
    ): "asked 3 questions in turn 1; turn-2 artifact is in two_turn_probe.md",
}


def rel(path: str | Path) -> str:
    candidate = Path(path)
    try:
        return str(candidate.resolve().relative_to(REPO_ROOT))
    except ValueError:
        return str(candidate)


def pct(rate: float | None) -> str:
    return "n/a" if rate is None else f"{rate * 100:.1f}%"


def ci(block: dict[str, Any]) -> str:
    if block.get("low") is None:
        return "n/a"
    return f"[{block['low'] * 100:.1f}%, {block['high'] * 100:.1f}%]"


def table(headers: Iterable[str], rows: Iterable[Iterable[Any]]) -> list[str]:
    header = "| " + " | ".join(headers) + " |"
    rule = "|" + "|".join("---" for _ in headers) + "|"
    body = ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return [header, rule, *body]


def render(analysis: dict[str, Any]) -> str:
    counts = analysis["counts"]
    corpus = analysis["corpus"]
    labels = corpus["labels"]
    spec = analysis["spec"]
    ctl = spec["arms"]["control"]
    exp = spec["arms"]["experiment"]
    snapshot = analysis["snapshot"]
    two_turn = analysis["two_turn"]
    verdict = analysis["verdict"]
    required = analysis["required_n"]
    kind = "full-run" if counts["pairs"] >= spec["n_min"] else "pilot"
    claim = (
        "No direction is claimed; the pre-registered n_min rule blocks one."
        if verdict == "INCONCLUSIVE"
        else f"The pre-registered rule fires in the `{verdict}` direction."
    )
    if verdict == "INCONCLUSIVE":
        rule_note = f"The pre-registered rule forbids a direction below `n_min = {spec['n_min']}`."
    else:
        rule_note = (
            f'The pre-registered rule fires; follow `judge_spec.verdicts["{verdict}"]`. '
            "The human-review dimensions stay unscored."
        )
    rollback_state = "triggered" if verdict == "ASK_FIRST" else "not triggered"
    rollback_intro = (
        "The rule fired in the ASK_FIRST direction; execute the steps below and keep the evidence."
        if verdict == "ASK_FIRST"
        else "No rollback action was taken. The apparatus and this report stay as evidence either way."
    )
    lines: list[str] = []

    lines += [
        f"# Ask-first vs artifact-first paired A/B — {kind} report",
        "",
        "Generated by `ab_analysis.py --write`; `--check` regenerates this file and fails on any drift.",
        "The report is computed from committed artifacts only and does not run a model.",
        "",
        f"**Verdict: `{verdict}`** — {analysis['verdict_reason']}. {claim}",
        "",
        "## Inputs",
        "",
    ]
    inputs = [
        ("corpus", analysis["paths"]["corpus"], analysis["hashes"]["corpus"]),
        ("judge_spec", analysis["paths"]["spec"], analysis["hashes"]["spec"]),
        (
            "control (pilot)",
            analysis["paths"]["control"],
            analysis["hashes"]["control"],
        ),
        (
            "experiment (pilot)",
            analysis["paths"]["experiment"],
            analysis["hashes"]["experiment"],
        ),
        (
            "protocol snapshot",
            analysis["paths"]["snapshot"],
            analysis["hashes"]["snapshot"],
        ),
        (
            "two-turn probe",
            analysis["paths"]["two_turn"],
            analysis["hashes"]["two_turn"],
        ),
        ("aggregate labels", analysis["paths"]["labels"], analysis["hashes"]["labels"]),
    ]
    lines += table(
        ("input", "path", "sha256"),
        [(name, f"`{rel(path)}`", f"`{digest}`") for name, path, digest in inputs],
    )
    lines += [
        "",
        "## 0. Pre-registered rule",
        "",
    ]
    rule_rows = [
        ("control arm", f"`{ctl['image']}` — ask-first, frozen protocol"),
        ("experiment arm", f"`{exp['image']}` — artifact-first onboarding bundle"),
        ("eligibility", spec["corpus"]["eligibility"]),
        ("success", spec["success"]["definition"]),
        ("failure", spec["failure"]["definition"]),
        ("manual_param_rate", spec["manual_param_rate"]["definition"]),
        (
            "primary test",
            f"exact McNemar, two-sided, alpha={spec['primary_test']['alpha']}; {spec['primary_test']['implementation']}",
        ),
        ("n_min", str(spec["n_min"])),
        ("verdict rule", spec["verdict_rule"]),
    ]
    lines += table(("item", "value"), rule_rows)
    lines += [
        "",
        "The two dimensions that cannot be automated are pre-registered as `human-review-needed` and are",
        "not part of the score: 「参数改动是否合理」 and 「first usable artifact 是否真可用」.",
        "",
        "## 1. Corpus composition and provenance",
        "",
    ]
    lines += table(
        ("source", "items", "share", "provenance"),
        [
            (
                "`frozen`",
                corpus["sources"].get("frozen", 0),
                pct(corpus["sources"].get("frozen", 0) / corpus["n"]),
                "copied byte-for-byte from `corpus40.jsonl` (open-ended + clarify_private)",
            ),
            (
                "`extended_generated`",
                corpus["sources"].get("extended_generated", 0),
                pct(corpus["sources"].get("extended_generated", 0) / corpus["n"]),
                "rendered by `gen_corpus_ab.py` from `gen_corpus40.py` family templates",
            ),
            (
                "`real_label_guided`",
                corpus["sources"].get("real_label_guided", 0),
                pct(corpus["sources"].get("real_label_guided", 0) / corpus["n"]),
                "same vocabulary; family counts from the exporter's aggregate labels",
            ),
            (
                "**total**",
                corpus["n"],
                "100.0%",
                "all items `open_ended: true`, all declare an artifact",
            ),
        ],
    )
    lines += [
        "",
        f"The frozen slice holds {len(corpus['frozen_origins'])} prompts: "
        + ", ".join(f"`{origin}`" for origin in corpus["frozen_origins"])
        + ". Five are the original frozen probes (c02, c03, c05, c06, c07); the other eleven were generated by",
        "`gen_corpus40.py` in Wave 0 and are copied here unchanged.",
        "",
        "### Aggregate-label guidance",
        "",
        f"`{rel(analysis['paths']['labels'])}` records {labels['n_total']} first messages from a developer harness",
        f"machine; {labels['none_count']} ({pct(labels['none_count'] / labels['n_total'])}) are labelled 都不是, leaving",
        f"{labels['labelled_total']} labelled artifact requests. The label-guided slice allocates 12 prompts by largest",
        "remainder over those counts:",
        "",
    ]
    label_rows = []
    for product, count in labels["counts"].items():
        label_rows.append(
            (
                product,
                count,
                pct(
                    count / labels["labelled_total"]
                    if labels["labelled_total"]
                    else None
                ),
                labels["allocation"].get(product, 0),
            )
        )
    lines += table(
        ("product label", "real count", "share of 140", "label-guided items"),
        label_rows,
    )
    lines += [
        "",
        "组合体检, 事件/宏观影响 and 交易复盘 receive zero label-guided seats at n=12 because their real",
        "shares are below one seat; they stay represented by the frozen and extended slices. The allocation is",
        "not a claim about novice users: the exporter's own note says the local store is a developer harness",
        "machine, and its raw text never entered the repository.",
        "",
        "### Honest provenance statement",
        "",
        "- Every prompt in `corpus_ab.jsonl` is produced by `gen_corpus_ab.py`; no generated prompt is a literal list.",
        "- The 16 frozen rows keep the exact `corpus40.jsonl` text; `gen_corpus_ab.py --check` proves the file is not stale.",
        "- The exporter's aggregate labels only chose the family mix of the `real_label_guided` slice; no raw message was read.",
        "- Expected-artifact mix: "
        + ", ".join(
            f"{name} {count}" for name, count in sorted(corpus["artifacts"].items())
        )
        + ".",
        "",
        "## 2. Control-arm fidelity",
        "",
        f"- Snapshot: `{analysis['snapshot']['file']}` (file sha256 `{analysis['hashes']['snapshot']}`).",
        f"- The spec records that same file digest (`{snapshot['file_sha256']}`); `ab_analysis.py` refuses to score if they diverge.",
        "- Frozen protocol blocks:",
        "",
    ]
    block_rows = [
        (block_id, block["source"], block["lines"], f"`{block['sha256']}`")
        for block_id, block in snapshot["blocks"].items()
    ]
    lines += table(("block", "source", "lines", "sha256"), block_rows)
    meta = analysis["baseline_meta"]
    lines += [
        "",
        f"- The control image is `{snapshot['image']}` (digest `{snapshot['image_digest']}`), built from commit",
        f"`{snapshot['source_commit']}`. `results/baseline_meta.json` records image `{meta.get('image_ref')}`, digest",
        f"`{meta.get('image_digest')}` and commit `{meta.get('git_commit')}` for the pilot run.",
        "- `tests/evals/intake/test_protocol_snapshot.py` recomputes both block digests from the fixture alone and",
        "  asserts the frozen constants. It must stay green; the control protocol cannot drift silently.",
        "- Therefore the control arm contains exactly the frozen ask-first protocol at the prompt level. This is",
        "  protocol-level fidelity, not a fresh image re-run: the pilot data was captured with that image on",
        f"  {meta.get('started_at')} .. {meta.get('finished_at')}.",
        "",
        "## 3. Pilot on committed data",
        "",
        "### 3.1 Raw per-item records",
        "",
    ]
    pilot_rows = []
    for cid in analysis["paired"]:
        left = analysis["rows"][cid]["control"]
        right = analysis["rows"][cid]["experiment"]
        note = " / ".join(
            text
            for arm, text in (
                ("control", PILOT_NOTES.get((cid, "control"))),
                ("experiment", PILOT_NOTES.get((cid, "experiment"))),
            )
            if text
        )
        pilot_rows.append(
            (
                cid,
                left["artifact_name"],
                left["route"],
                "yes" if left["params"] is True else "no",
                left["turns"] if left["turns"] is not None else "?",
                "yes" if left["success"] else "no",
                "yes" if left["manual"] else "no",
                right["route"],
                "yes" if right["params"] is True else "no",
                right["turns"] if right["turns"] is not None else "?",
                "yes" if right["success"] else "no",
                "yes" if right["manual"] else "no",
                note or "—",
            )
        )
    lines += table(
        (
            "id",
            "artifact",
            "ctl route",
            "ctl params",
            "ctl turns",
            "ctl S",
            "ctl M",
            "exp route",
            "exp params",
            "exp turns",
            "exp S",
            "exp M",
            "notes",
        ),
        pilot_rows,
    )
    lines += [
        "",
        "`S` = success proxy (execution route + retrievable parameters + <=2 turns). `M` = manual parameter",
        "completion proxy (question call, or clarification route without compiled parameters). Neither column",
        "is a human judgement.",
        "",
        "### 3.2 Excluded routing controls",
        "",
    ]
    excluded_rows = []
    for cid in analysis["excluded"]:
        left = analysis["rows"][cid]["control"]
        right = analysis["rows"][cid]["experiment"]
        note = (
            "refusal request"
            if left["expected"] == "refuse"
            else "direct-answer request"
        )
        if cid == "c10" and right["route"] == "clarify_private":
            note += "; experiment answers a refusal with options (misroute)"
        excluded_rows.append(
            (cid, left["expected"], left["route"], right["route"], note)
        )
    lines += table(
        ("id", "expected class", "ctl route", "exp route", "why excluded"),
        excluded_rows,
    )
    if analysis["dropped"]:
        lines += [
            "",
            "Dropped ids (present in one arm only or missing a layer): "
            + ", ".join(f"`{cid}`" for cid in analysis["dropped"])
            + ". `c27` is the extra item the wave-1 probe added; it has no control record and is not a pair.",
        ]
    lines += [
        "",
        "### 3.3 Raw counts before any inference",
        "",
        f"- Paired ids: **{counts['pairs']}** ("
        + ", ".join(f"`{cid}`" for cid in analysis["paired"])
        + ").",
        f"- Eligible artifact-bearing pairs: **{counts['eligible']}**; excluded routing controls: {len(analysis['excluded'])}.",
        f"- Control: **{counts['control_success']}/{counts['eligible']} success**, **{counts['control_manual']}/{counts['eligible']} manual parameter completion**.",
        f"- Experiment: **{counts['experiment_success']}/{counts['eligible']} success**, **{counts['experiment_manual']}/{counts['eligible']} manual parameter completion**.",
        f"- Discordant pairs: control-only **{counts['b']}**, experiment-only **{counts['c']}**.",
        f"- Exact McNemar two-sided p: **{counts['p_value']}**.",
        f"- Required N from the observed discordance (alpha={spec['primary_test']['alpha']}, power={spec['required_n']['power']}): "
        + (
            f"**{required}** pairs."
            if required is not None
            else "not estimable (no discordance)."
        ),
        "",
        "### 3.4 Descriptive rates with Wilson 95% CI (no claim)",
        "",
    ]
    lines += table(
        ("measure", "control", "experiment"),
        [
            (
                "success",
                f"{counts['control_success']}/{counts['eligible']} = {pct(counts['control_success_ci']['rate'])} {ci(counts['control_success_ci'])}",
                f"{counts['experiment_success']}/{counts['eligible']} = {pct(counts['experiment_success_ci']['rate'])} {ci(counts['experiment_success_ci'])}",
            ),
            (
                "failure (manual parameter)",
                f"{counts['control_manual']}/{counts['eligible']} = {pct(counts['control_manual_ci']['rate'])} {ci(counts['control_manual_ci'])}",
                f"{counts['experiment_manual']}/{counts['eligible']} = {pct(counts['experiment_manual_ci']['rate'])} {ci(counts['experiment_manual_ci'])}",
            ),
        ],
    )
    lines += [
        "",
        "Under the pre-registered rule the failure rate is the manual-parameter rate; the two columns stay",
        "separate and are not collapsed. The intervals are wider than the observed difference in both",
        "directions; they are shown only so the raw counts are not converted into a bare percentage claim.",
        "",
        "### 3.5 Why these 10 cannot settle it",
        "",
        f"- `n_pairs = {counts['pairs']}` is below the pre-registered `n_min = {spec['n_min']}`; only {counts['eligible']} pairs are artifact-bearing.",
        f"- Only {len(analysis['pilot_in_corpus'])} of the {corpus['n']} corpus items ("
        + ", ".join(f"`{cid}`" for cid in analysis["pilot_in_corpus"])
        + ") have committed pairs; the full run needs the other items.",
        "- The committed runs are single-turn records; the harness cannot observe a turn-2 artifact inside this JSONL.",
        "- The control image predates the intake skill, so the contrast is protocol-level (frozen ask-first text) plus the onboarding bundle.",
        f"- One discordant pair with a zero cell gives an exact p of {counts['p_value']} and a planning N of {required if required is not None else 'n/a'}; neither supports a direction.",
        "",
        "## 4. human-review-needed items (named, not scored)",
        "",
        "### 4.1 「参数改动是否合理」",
        "",
        "Items where parameters were compiled without asking: control "
        + ", ".join(f"`{cid}`" for cid in _named_params(analysis, "control"))
        + "; experiment "
        + ", ".join(f"`{cid}`" for cid in _named_params(analysis, "experiment"))
        + ".",
        "",
        "Flag: `human-review-needed`. The JSONL holds tool names and argument digests, not whether the declared",
        "market, horizon, risk or holdings default matches the user's intent. Not scored; no verdict contribution.",
        "",
        "### 4.2 「first usable artifact 是否真可用」",
        "",
        "Items counted as automated successes: control "
        + ", ".join(f"`{cid}`" for cid in _named_success(analysis, "control"))
        + "; experiment "
        + ", ".join(f"`{cid}`" for cid in _named_success(analysis, "experiment"))
        + ".",
        "",
        "Flag: `human-review-needed`. The event contract records that an execution route and parameters existed,",
        "not that the stored artifact is complete and usable. Committed cross-checks already show the gap:",
        "`results/wave1_frozen10_report.md` records experiment `c02` produced no artifact (600 s cap, truncated",
        "mid-tool-loop) while the proxy counts it a success, and records `c27` rewrote the T-1 cutoff. Experiment",
        "`c05` asked in turn 1 and the two-turn probe found its artifact in turn 2, so its automated failure may",
        "be a false negative. These are pointers for a human, not scores.",
        "",
        "## 5. Turn-level evidence: the two-turn probe",
        "",
        f"`{rel(analysis['paths']['two_turn'])}` is the only turn-level evidence available. It is one session, not a pair.",
        "",
    ]
    lines += table(
        ("field", "value"),
        [
            ("session", f"`{two_turn.get('session_id')}`"),
            ("user turns", two_turn.get("user_turns")),
            ("turn-1 questions", two_turn.get("turn1_questions")),
            ("options per question", two_turn.get("turn1_options_per_question")),
            ("escape hatch", two_turn.get("turn1_escape_hatch")),
            ("turn-2 wall", f"{two_turn.get('turn2_wall_s')} s"),
            (
                "artifact",
                f"`{two_turn.get('artifact_path')}` ({two_turn.get('artifact_bytes')} bytes, {two_turn.get('artifact_lines')} lines)",
            ),
            ("closing block complete", two_turn.get("closing_complete")),
            ("continuation supported", two_turn.get("continuation_supported")),
        ],
    )
    lines += [
        "",
        "It proves the ask-first path can close inside two user turns on this harness. It cannot say whether",
        "artifact-first would have been faster or whether the artifact is better; those remain the two",
        "`human-review-needed` dimensions.",
        "",
        "## 6. Verdict and the full run",
        "",
        f"**`{verdict}`** — {analysis['verdict_reason']}. {rule_note}",
        f"The planning estimate is {required if required is not None else 'not estimable'} pairs from the",
        "observed discordance; it is unstable with one discordant pair and one zero cell. The corpus holds",
        f"{corpus['n']} items, so even a full run reaches {corpus['n']} pairs; a planning N above that is another",
        "reason the estimate is only a note, not a promise.",
        "",
        "When a faster machine is available, run the 40-item corpus on both arms and re-score:",
        "",
        "```bash",
        "cd OpencodeAgent",
        "# one container per image, server on :4096; the names below are the docker exec targets",
        "# control: image opencode-serve:v3.10.0-mymain",
        "python tests/evals/intake/ab/run_ab.py --container opencode-ab-control \\",
        "  --corpus tests/evals/intake/ab/corpus_ab.jsonl \\",
        "  --out tests/evals/intake/ab/control_full.jsonl \\",
        "  --text-out tests/evals/intake/ab/texts_control",
        "# experiment: image opencode-serve:v3.11.1-onboarding-20261028-71572199-fix1",
        "python tests/evals/intake/ab/run_ab.py --container opencode-ab-experiment \\",
        "  --corpus tests/evals/intake/ab/corpus_ab.jsonl \\",
        "  --out tests/evals/intake/ab/experiment_full.jsonl \\",
        "  --text-out tests/evals/intake/ab/texts_experiment",
        "python tests/evals/intake/ab/ab_analysis.py \\",
        "  --control tests/evals/intake/ab/control_full.jsonl \\",
        "  --experiment tests/evals/intake/ab/experiment_full.jsonl \\",
        "  --corpus tests/evals/intake/ab/corpus_ab.jsonl --write",
        "```",
        "",
        "`run_ab.py` is a thin wrapper over the tested `run.py` single-item runner: `run.py`'s custom-corpus",
        "contract requires `cNN` ids and two negative items, which does not fit this `aNN` open-type corpus.",
        "Container readiness follows the startup-probe discipline in `OpencodeAgent/AGENTS.md` §10.",
        "",
        "## 7. Limitations",
        "",
        "- 10-pair pilot, 7 eligible pairs; the committed corpus coverage is 5/40.",
        "- Single-turn corpus records cannot observe turn 2; the two-turn probe is n=1 and is not a pair.",
        "- The success definition cannot distinguish 「asked correctly」 from 「failed to produce」; that is exactly why the plan asks for the `human-review-needed` flag.",
        "- Artifact usability and default appropriateness are not automatable from the event JSONL.",
        "- The control image predates the intake skill; the experiment fix1 image digest is not in committed metadata, so the arm is identified by its immutable tag.",
        "- The label mix comes from a developer harness machine, not a novice-user sample.",
        "- The 600 s per-item cap and the machine's inference throughput are why this is bounded evidence, not a full run.",
        "",
        f"## 8. Rollback steps pre-written ({rollback_state})",
        "",
        "Rollback is triggered only when the pre-registered rule returns ASK_FIRST (n>=30, p<0.05, experiment-only > control-only).",
        "If that happens:",
        "",
    ]
    for index, step in enumerate(spec["rollback_if_ask_first"], 1):
        lines.append(f"{index}. {step}")
    lines += [
        "",
        rollback_intro,
        "",
    ]
    return "\n".join(lines)


def _named_params(analysis: dict[str, Any], arm: str) -> list[str]:
    return [
        cid
        for cid in analysis["eligible"]
        if analysis["rows"][cid][arm]["route"] == "execute_with_defaults"
        and analysis["rows"][cid][arm]["params"] is True
    ]


def _named_success(analysis: dict[str, Any], arm: str) -> list[str]:
    return [
        cid for cid in analysis["eligible"] if analysis["rows"][cid][arm]["success"]
    ]
