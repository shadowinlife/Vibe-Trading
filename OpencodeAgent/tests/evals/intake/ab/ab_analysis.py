"""Score the paired ask-first vs artifact-first A/B and render ``ab_report.md``.

Corpus composition (built by ``gen_corpus_ab.py``; no prompt is hand-written here):
- ``frozen`` 16: every ``open_ended`` / ``clarify_private`` item copied from
  ``corpus40.jsonl``. Five are the original frozen probes (c02, c03, c05, c06,
  c07); eleven were already generated by ``gen_corpus40.py`` and are frozen here
  as committed inputs (c14, c15, c16, c19, c20, c21, c22, c26, c27, c28, c29).
- ``extended_generated`` 12: rendered from ``gen_corpus40.FAMILIES`` templates
  and slot vocabularies with a new seed.
- ``real_label_guided`` 12: rendered from the same vocabulary; the per-product
  counts are allocated by largest remainder over the 140 non-"都不是" first
  messages in ``results/request_labels.json`` (个股体检 1, 选股清单 1,
  策略回测 5, 组合体检 0, 事件/宏观影响 0, 交易复盘 0, 定时监控 3, 报告 2 at
  n=12; the zero-seat families stay represented by the frozen/extended slices).

The analysis is standard library only. The exact McNemar tail is imported from
``analyze_wave1.py`` (never re-implemented). ``--check`` regenerates the report
in memory and fails on any drift; ``--write`` replaces ``ab_report.md``.

Committed pilot: control = ``results/baseline.jsonl`` (image
``opencode-serve:v3.10.0-mymain``), experiment = ``results/wave1_probe.jsonl``
(image ``opencode-serve:v3.11.1-onboarding-20261028-71572199-fix1``). The pilot
has 10 paired ids, 7 of them artifact-bearing. It is reported, not judged: the
pre-registered ``n_min`` is 30, so the verdict is INCONCLUSIVE.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import re
import sys
from collections import Counter
from pathlib import Path
from statistics import NormalDist
from typing import Any

BASE_DIR = Path(__file__).resolve().parent
INTAKE_DIR = BASE_DIR.parent
DEFAULT_CONTROL = INTAKE_DIR / "results" / "baseline.jsonl"
DEFAULT_EXPERIMENT = INTAKE_DIR / "results" / "wave1_probe.jsonl"
DEFAULT_CORPUS = BASE_DIR / "corpus_ab.jsonl"
DEFAULT_SPEC = BASE_DIR / "judge_spec.json"
DEFAULT_REPORT = BASE_DIR / "ab_report.md"
DEFAULT_SNAPSHOT = INTAKE_DIR / "fixtures" / "ask_first_protocol_snapshot.md"
DEFAULT_TWO_TURN = INTAKE_DIR / "results" / "two_turn_probe.md"
DEFAULT_LABELS = INTAKE_DIR / "results" / "request_labels.json"
DEFAULT_BASELINE_META = INTAKE_DIR / "results" / "baseline_meta.json"
DEFAULT_EXPECTED = INTAKE_DIR / "expected.json"

if str(INTAKE_DIR) not in sys.path:
    sys.path.insert(0, str(INTAKE_DIR))

from analyze_wave1 import mcnemar_exact, wilson  # noqa: E402

EVENTS = ("route_class", "intake_loaded", "question_called", "params_compiled")
ARTIFACT_ROUTES = ("execute_with_defaults", "clarify_private")
SOURCES = ("frozen", "extended_generated", "real_label_guided")
REQUIRED_FIELDS = (
    "id",
    "prompt",
    "source",
    "expected_artifact",
    "open_ended",
    "rationale",
)
TWO_TURN_RE = re.compile(r"<!-- two-turn:json\n(?P<payload>.*?)\n-->", re.DOTALL)


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    return [
        json.loads(line)
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def group_events(path: Path) -> dict[str, dict[str, dict[str, Any]]]:
    groups: dict[str, dict[str, dict[str, Any]]] = {}
    seen: set[tuple[str, str]] = set()
    for record in load_jsonl(path):
        key = (record["corpus_id"], record["event"])
        if key in seen:
            raise SystemExit(f"{path}: duplicate event {key}")
        seen.add(key)
        groups.setdefault(record["corpus_id"], {})[record["event"]] = record
    return groups


def _first_turns(records: dict[str, dict[str, Any]]) -> int | None:
    for event in EVENTS:
        record = records.get(event) or {}
        if record.get("user_turns") is not None:
            return int(record["user_turns"])
    return None


def score_arm(
    groups: dict[str, dict[str, dict[str, Any]]],
) -> dict[str, dict[str, Any]]:
    """Apply the pre-registered success/failure proxies to one arm."""
    rows: dict[str, dict[str, Any]] = {}
    for corpus_id, records in groups.items():
        route = records.get("route_class")
        if route is None:
            continue
        expected = route.get("expected")
        artifact = expected in ARTIFACT_ROUTES
        complete = all(event in records for event in EVENTS)
        params = records.get("params_compiled") or {}
        question = records.get("question_called") or {}
        turns = _first_turns(records)
        params_ok = params.get("observed") is True
        observed = route.get("observed")
        success = bool(
            artifact
            and complete
            and observed == "execute_with_defaults"
            and params_ok
            and turns is not None
            and turns <= 2
        )
        manual = bool(
            artifact
            and complete
            and (
                question.get("observed") is True
                or (observed == "clarify_private" and not params_ok)
            )
        )
        rows[corpus_id] = {
            "expected": expected,
            "artifact": artifact,
            "complete": complete,
            "route": observed,
            "params": params.get("observed"),
            "question": question.get("observed"),
            "turns": turns,
            "success": success,
            "manual": manual,
        }
    return rows


def validate_corpus(items: list[dict[str, Any]]) -> list[str]:
    errors: list[str] = []
    if len(items) < 30:
        errors.append(f"corpus must hold at least 30 items, found {len(items)}")
    ids: list[str] = []
    for index, item in enumerate(items, 1):
        label = str(item.get("id") or f"line {index}")
        errors.extend(
            f"{label}: missing or empty field {key!r}"
            for key in REQUIRED_FIELDS
            if not item.get(key)
        )
        if not re.fullmatch(r"a\d{2}", str(item.get("id", ""))):
            errors.append(f"{label}: id must match aNN")
        if item.get("open_ended") is not True:
            errors.append(f"{label}: open_ended must be true")
        if item.get("expected_artifact") in (None, "", "none"):
            errors.append(f"{label}: expected_artifact must name an artifact")
        if item.get("source") not in SOURCES:
            errors.append(f"{label}: source must be one of {SOURCES}")
        if isinstance(item.get("id"), str):
            ids.append(item["id"])
    if len(set(ids)) != len(ids):
        errors.append("corpus has duplicate ids")
    sources = {item.get("source") for item in items}
    if len(sources) < 3:
        errors.append(f"corpus must use at least 3 sources, found {sorted(sources)}")
    return errors


def required_n(b: int, c: int, n: int, alpha: float, power: float) -> int | None:
    if n <= 0 or b == c:
        return None
    z_alpha = NormalDist().inv_cdf(1 - alpha / 2)
    z_power = NormalDist().inv_cdf(power)
    return math.ceil((z_alpha + z_power) ** 2 * n * (b + c) / (b - c) ** 2)


def decide(
    n_pairs: int, p_value: float, b: int, c: int, n_min: int, alpha: float
) -> tuple[str, str]:
    if n_pairs < n_min:
        return "INCONCLUSIVE", f"n_pairs={n_pairs} < n_min={n_min}"
    if p_value < alpha and b > c:
        return (
            "ARTIFACT_FIRST",
            f"p={p_value} < {alpha}, control-only {b} > experiment-only {c}",
        )
    if p_value < alpha and c > b:
        return (
            "ASK_FIRST",
            f"p={p_value} < {alpha}, experiment-only {c} > control-only {b}",
        )
    if p_value < alpha:
        return "INCONCLUSIVE", f"p={p_value} < {alpha} but the discordance is tied"
    return "NO_SIGNIFICANT_DIFFERENCE", f"p={p_value} >= {alpha}"


def _two_turn(path: Path) -> dict[str, Any]:
    match = TWO_TURN_RE.search(path.read_text(encoding="utf-8"))
    if not match:
        raise SystemExit(f"{path}: missing <!-- two-turn:json ... --> block")
    return json.loads(match.group("payload"))


def _label_stats(corpus: list[dict[str, Any]], labels_path: Path) -> dict[str, Any]:
    payload = json.loads(labels_path.read_text(encoding="utf-8"))
    counts: dict[str, int] = payload["label_distribution"]
    products = (
        "个股体检",
        "选股清单",
        "策略回测",
        "组合体检",
        "事件/宏观影响",
        "交易复盘",
        "定时监控",
        "报告",
    )
    artifact_labels = [name for name in products if name in counts]
    labelled_total = sum(counts[name] for name in artifact_labels)
    allocation = Counter(
        item["expected_artifact"]
        for item in corpus
        if item["source"] == "real_label_guided"
    )
    return {
        "n_total": payload.get("n_total"),
        "counts": {name: counts.get(name, 0) for name in artifact_labels},
        "labelled_total": labelled_total,
        "none_count": counts.get("都不是", 0),
        "allocation": {name: allocation.get(name, 0) for name in artifact_labels},
        "notes": payload.get("notes", ""),
    }


def analyze(
    control_path: Path, experiment_path: Path, corpus_path: Path, spec_path: Path
) -> dict[str, Any]:
    spec = json.loads(spec_path.read_text(encoding="utf-8"))
    n_min = int(spec["n_min"])
    alpha = float(spec["primary_test"]["alpha"])
    power = float(spec["required_n"]["power"])

    corpus = load_jsonl(corpus_path)
    problems = validate_corpus(corpus)
    if problems:
        raise SystemExit("\n".join(f"[corpus] {problem}" for problem in problems))

    control = score_arm(group_events(control_path))
    experiment = score_arm(group_events(experiment_path))
    paired = [
        cid
        for cid in sorted(set(control) & set(experiment))
        if control[cid]["complete"] and experiment[cid]["complete"]
    ]
    dropped = sorted((set(control) | set(experiment)) - set(paired))
    product_by_id = {item["id"]: item["expected_artifact"] for item in corpus}
    product_by_origin = {
        item["origin_id"]: item["expected_artifact"]
        for item in corpus
        if item.get("origin_id")
    }
    frozen_products = {
        cid: detail.get("expected_product")
        for cid, detail in json.loads(
            DEFAULT_EXPECTED.read_text(encoding="utf-8")
        ).items()
    }
    for cid in paired:
        name = (
            product_by_id.get(cid)
            or product_by_origin.get(cid)
            or frozen_products.get(cid)
            or "none"
        )
        control[cid]["artifact_name"] = name
        experiment[cid]["artifact_name"] = name

    eligible: list[str] = []
    mismatched: list[str] = []
    excluded: list[str] = []
    for cid in paired:
        left, right = control[cid], experiment[cid]
        if not (left["artifact"] and right["artifact"]):
            excluded.append(cid)
        elif left["expected"] != right["expected"]:
            mismatched.append(cid)
        else:
            eligible.append(cid)

    n = len(eligible)
    ctl_success = sum(control[cid]["success"] and cid in eligible for cid in paired)
    exp_success = sum(experiment[cid]["success"] and cid in eligible for cid in paired)
    ctl_manual = sum(control[cid]["manual"] and cid in eligible for cid in paired)
    exp_manual = sum(experiment[cid]["manual"] and cid in eligible for cid in paired)
    b = sum(
        control[cid]["success"] and not experiment[cid]["success"] for cid in eligible
    )
    c = sum(
        experiment[cid]["success"] and not control[cid]["success"] for cid in eligible
    )
    p_value = mcnemar_exact(b, c)
    verdict, reason = decide(len(paired), p_value, b, c, n_min, alpha)

    corpus_ids = {item["id"] for item in corpus}
    corpus_origins = {item.get("origin_id") for item in corpus if item.get("origin_id")}
    pilot_in_corpus = [
        cid for cid in paired if cid in corpus_ids or cid in corpus_origins
    ]
    snapshots = spec["arms"]["control"]
    snapshot_digest = sha256_file(DEFAULT_SNAPSHOT)
    if snapshot_digest != snapshots["protocol_snapshot_sha256"]:
        raise SystemExit(
            "control snapshot drift: "
            f"{DEFAULT_SNAPSHOT} is {snapshot_digest}, spec records {snapshots['protocol_snapshot_sha256']}"
        )

    return {
        "paths": {
            "control": str(control_path),
            "experiment": str(experiment_path),
            "corpus": str(corpus_path),
            "spec": str(spec_path),
            "snapshot": str(DEFAULT_SNAPSHOT),
            "two_turn": str(DEFAULT_TWO_TURN),
            "labels": str(DEFAULT_LABELS),
            "baseline_meta": str(DEFAULT_BASELINE_META),
        },
        "hashes": {
            "control": sha256_file(control_path),
            "experiment": sha256_file(experiment_path),
            "corpus": sha256_file(corpus_path),
            "spec": sha256_file(spec_path),
            "snapshot": snapshot_digest,
            "two_turn": sha256_file(DEFAULT_TWO_TURN),
            "labels": sha256_file(DEFAULT_LABELS),
        },
        "spec": spec,
        "corpus": {
            "n": len(corpus),
            "sources": Counter(item["source"] for item in corpus),
            "artifacts": Counter(item["expected_artifact"] for item in corpus),
            "frozen_origins": sorted(
                item["origin_id"] for item in corpus if item.get("origin_id")
            ),
            "labels": _label_stats(corpus, DEFAULT_LABELS),
        },
        "rows": {
            cid: {"control": control[cid], "experiment": experiment[cid]}
            for cid in paired
        },
        "paired": paired,
        "eligible": eligible,
        "excluded": excluded,
        "mismatched": mismatched,
        "dropped": dropped,
        "pilot_in_corpus": pilot_in_corpus,
        "counts": {
            "pairs": len(paired),
            "eligible": n,
            "control_success": ctl_success,
            "experiment_success": exp_success,
            "control_manual": ctl_manual,
            "experiment_manual": exp_manual,
            "b": b,
            "c": c,
            "p_value": p_value,
            "control_success_ci": wilson(ctl_success, n),
            "experiment_success_ci": wilson(exp_success, n),
            "control_manual_ci": wilson(ctl_manual, n),
            "experiment_manual_ci": wilson(exp_manual, n),
        },
        "required_n": required_n(b, c, n, alpha, power),
        "verdict": verdict,
        "verdict_reason": reason,
        "snapshot": {
            "file": snapshots["protocol_snapshot"],
            "file_sha256": snapshots["protocol_snapshot_sha256"],
            "blocks": snapshots["protocol_blocks"],
            "image": snapshots["image"],
            "image_digest": snapshots["image_digest"],
            "source_commit": snapshots["source_commit"],
        },
        "baseline_meta": json.loads(DEFAULT_BASELINE_META.read_text(encoding="utf-8")),
        "two_turn": _two_turn(DEFAULT_TWO_TURN),
        "experiment_image": spec["arms"]["experiment"]["image"],
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--control", default=str(DEFAULT_CONTROL), help="control-arm JSONL"
    )
    parser.add_argument(
        "--experiment", default=str(DEFAULT_EXPERIMENT), help="experiment-arm JSONL"
    )
    parser.add_argument(
        "--corpus", default=str(DEFAULT_CORPUS), help="A/B corpus JSONL"
    )
    parser.add_argument(
        "--spec", default=str(DEFAULT_SPEC), help="pre-registered judge_spec.json"
    )
    parser.add_argument("--report", default=str(DEFAULT_REPORT), help="report path")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write", action="store_true", help="write the report")
    group.add_argument(
        "--check", action="store_true", help="fail if the report is stale"
    )
    args = parser.parse_args(argv)

    analysis = analyze(
        Path(args.control), Path(args.experiment), Path(args.corpus), Path(args.spec)
    )
    from ab_report import render

    rendered = render(analysis)
    counts = analysis["counts"]
    print(
        f"[ab] pairs={counts['pairs']} eligible={counts['eligible']} "
        f"control_success={counts['control_success']} experiment_success={counts['experiment_success']} "
        f"control_manual={counts['control_manual']} experiment_manual={counts['experiment_manual']} "
        f"mcnemar_p={counts['p_value']} verdict={analysis['verdict']}"
    )
    report_path = Path(args.report)
    if args.write:
        report_path.write_text(rendered, encoding="utf-8")
        print(f"[ab] wrote {report_path}")
        return 0
    current = report_path.read_text(encoding="utf-8") if report_path.is_file() else ""
    if current == rendered:
        print(f"[ab] {report_path}: up to date")
        return 0
    import difflib

    diff = list(
        difflib.unified_diff(
            current.splitlines(),
            rendered.splitlines(),
            fromfile=str(report_path),
            tofile="regenerated",
            lineterm="",
        )
    )
    print("\n".join(diff[:60]), file=sys.stderr)
    print(f"[ab] {report_path} is stale; rerun with --write", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
