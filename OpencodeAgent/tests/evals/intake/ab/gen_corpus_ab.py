"""Generate the ask-first vs artifact-first paired A/B corpus.

WHY: todo 14 needs at least 30 open-type prompts. Three slices make the 35-item
corpus, and no prompt is hand-written here:

- ``frozen`` (16): copied byte-for-byte from ``corpus40.jsonl`` -- every item
  marked ``open_ended: true`` (c02, c03, c07 and c14, c15, c16, c20, c21) plus
  every ``clarify_private`` item (c05, c06, c19, c22, c26, c27, c28, c29).
  Five of them are the original frozen probes; the other eleven were already
  generated by ``gen_corpus40.py`` and are frozen here as committed inputs.
- ``extended_generated`` (12): rendered from the existing family templates and
  slot vocabularies in ``gen_corpus40.py`` with a new seed. The plan covers the
  product families that the frozen slice does not reach.
- ``real_label_guided`` (12): rendered from the same vocabulary, but the number
  of prompts per product is allocated by largest remainder over the aggregate
  first-message labels in ``results/request_labels.json`` (the 140 messages not
  labelled "都不是"). No raw user text is read, only the aggregate counts.

``open_ended`` in this corpus means "A/B-eligible": an artifact-bearing request
whose parameters are not fully specified, so either protocol must ask or choose
defaults. For frozen items it is the union of corpus40's ``open_ended: true``
and ``expect == "clarify_private"``; direct-answer and refusal items are
deliberately absent because neither arm should produce an artifact for them.

Run ``python gen_corpus_ab.py`` to write ``corpus_ab.jsonl`` and
``python gen_corpus_ab.py --check`` to prove the file is not stale.
"""

from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path
from typing import Any

BASE_DIR = Path(__file__).resolve().parent
INTAKE_DIR = BASE_DIR.parent
OUTPUT_PATH = BASE_DIR / "corpus_ab.jsonl"
CORPUS40_PATH = INTAKE_DIR / "corpus40.jsonl"
LABELS_PATH = INTAKE_DIR / "results" / "request_labels.json"

if str(INTAKE_DIR) not in sys.path:
    sys.path.insert(0, str(INTAKE_DIR))

import gen_corpus40 as vocab  # noqa: E402

EXTENDED_SEED = vocab.SEED + 101
LABEL_SEED = vocab.SEED + 202
LABEL_GUIDED_COUNT = 12
PRODUCTS = (
    "个股体检",
    "选股清单",
    "策略回测",
    "组合体检",
    "事件/宏观影响",
    "交易复盘",
    "定时监控",
    "报告",
)

# (family index in gen_corpus40.FAMILIES, number of prompts). Families 10/11
# are direct-answer and refusal and are intentionally not used here.
EXTENDED_PLAN: tuple[tuple[int, int], ...] = (
    (0, 1),  # 个股体检, execute_with_defaults
    (1, 2),  # 选股清单, execute_with_defaults
    (2, 2),  # 策略回测, execute_with_defaults
    (3, 1),  # 组合体检, clarify_private
    (4, 1),  # 事件/宏观影响, execute_with_defaults
    (5, 1),  # 交易复盘, clarify_private
    (6, 1),  # 定时监控, execute_with_defaults
    (7, 1),  # 报告, execute_with_defaults
    (8, 1),  # 个股体检, clarify_private
    (9, 1),  # 组合体检, clarify_private
)


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    return [
        json.loads(line)
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def frozen_items() -> list[dict[str, Any]]:
    selected = [
        item
        for item in load_jsonl(CORPUS40_PATH)
        if item.get("open_ended") is True or item.get("expect") == "clarify_private"
    ]
    if len(selected) != 16:
        raise SystemExit(
            f"expected 16 frozen open-type items in corpus40.jsonl, found {len(selected)}"
        )
    return selected


def _family_render(family_index: int, occurrence: int, rng: Any) -> str:
    _expect, _product, _open_ended, _count, templates, slots = vocab.FAMILIES[
        family_index
    ]
    return vocab._render(rng, templates[occurrence % len(templates)], slots)


def _render_unique(family_index: int, occurrence: int, rng: Any, seen: set[str]) -> str:
    """Render until the prompt is new; a duplicate would pad the corpus."""
    for attempt in range(40):
        prompt = _family_render(family_index, occurrence + attempt, rng)
        if prompt not in seen:
            seen.add(prompt)
            return prompt
    raise SystemExit(f"could not render a unique prompt for family {family_index}")


def extended_items(seen: set[str]) -> list[dict[str, Any]]:
    rng = random.Random(EXTENDED_SEED)
    items: list[dict[str, Any]] = []
    for family_index, count in EXTENDED_PLAN:
        expect, product, _open_ended, _family_count, _templates, _slots = (
            vocab.FAMILIES[family_index]
        )
        for occurrence in range(count):
            items.append(
                {
                    "prompt": _render_unique(family_index, occurrence, rng, seen),
                    "source": "extended_generated",
                    "expected_artifact": product,
                    "expect": expect,
                    "rationale": (
                        f"generated from the gen_corpus40.py family vocabulary "
                        f"({product}, {expect}); seed={EXTENDED_SEED}"
                    ),
                    "generator": f"gen_corpus_ab.py extended seed={EXTENDED_SEED}",
                }
            )
    if len(items) != 12:
        raise SystemExit(f"extended slice must hold 12 items, built {len(items)}")
    return items


def largest_remainder(counts: dict[str, int], total: int) -> dict[str, int]:
    """Allocate ``total`` seats over ``counts`` proportionally, floors first."""
    population = sum(counts[label] for label in PRODUCTS)
    if population <= 0:
        raise SystemExit(f"{LABELS_PATH} has no labelled artifact requests")
    quota = {label: counts[label] / population * total for label in PRODUCTS}
    seats = {label: int(quota[label]) for label in PRODUCTS}
    remaining = total - sum(seats.values())
    for label in sorted(
        PRODUCTS, key=lambda name: (quota[name] - seats[name], name), reverse=True
    )[:remaining]:
        seats[label] += 1
    return seats


def label_guided_items(seen: set[str]) -> list[dict[str, Any]]:
    labels = json.loads(LABELS_PATH.read_text(encoding="utf-8"))["label_distribution"]
    labelled_total = sum(labels[label] for label in PRODUCTS)
    seats = largest_remainder(labels, LABEL_GUIDED_COUNT)
    rng = random.Random(LABEL_SEED)
    items: list[dict[str, Any]] = []
    for product in PRODUCTS:
        families = [
            index for index, family in enumerate(vocab.FAMILIES) if family[1] == product
        ]
        if not families:
            raise SystemExit(
                f"gen_corpus40.FAMILIES has no family for product {product!r}"
            )
        for occurrence in range(seats[product]):
            family_index = families[occurrence % len(families)]
            expect = vocab.FAMILIES[family_index][0]
            share = f"{labels[product]}/{labelled_total} = {labels[product] / labelled_total * 100:.1f}%"
            items.append(
                {
                    "prompt": _render_unique(family_index, occurrence, rng, seen),
                    "source": "real_label_guided",
                    "expected_artifact": product,
                    "expect": expect,
                    "rationale": (
                        f"generated from the gen_corpus40.py vocabulary; family {product} selected by "
                        f"the exporter's aggregate label share ({share} of non-都不是 first messages)"
                    ),
                    "generator": f"gen_corpus_ab.py label-guided seed={LABEL_SEED}",
                }
            )
    if len(items) != LABEL_GUIDED_COUNT:
        raise SystemExit(
            f"label-guided slice must hold {LABEL_GUIDED_COUNT} items, built {len(items)}"
        )
    return items


def build_items() -> list[dict[str, Any]]:
    items: list[dict[str, Any]] = []
    seen: set[str] = set()
    for item in frozen_items():
        if item["prompt"] in seen:
            raise SystemExit(f"duplicate frozen prompt: {item['prompt']!r}")
        seen.add(item["prompt"])
        items.append(
            {
                "prompt": item["prompt"],
                "source": "frozen",
                "expected_artifact": item["expected_product"],
                "expect": item["expect"],
                "origin_id": item["id"],
                "rationale": (
                    f"copied verbatim from corpus40.jsonl {item['id']} "
                    f"({item['expect']}, {item['expected_product']}); open-type = "
                    f"open_ended={item['open_ended']} or clarify_private"
                ),
                "generator": "corpus40.jsonl (verbatim)",
            }
        )
    items.extend(extended_items(seen))
    items.extend(label_guided_items(seen))
    for index, item in enumerate(items, 1):
        item["id"] = f"a{index:02d}"
        item["open_ended"] = True
        item["negative"] = False
        item["expected_product"] = item["expected_artifact"]
    return items


def render_corpus() -> str:
    return "".join(
        json.dumps(item, ensure_ascii=False) + "\n" for item in build_items()
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify corpus_ab.jsonl matches regeneration",
    )
    args = parser.parse_args(argv)
    rendered = render_corpus()
    if args.check:
        current = (
            OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.exists() else ""
        )
        if current != rendered:
            print(f"{OUTPUT_PATH} is stale; rerun gen_corpus_ab.py", file=sys.stderr)
            return 1
        print(
            f"{OUTPUT_PATH}: {len(rendered.splitlines())} items, regeneration matches"
        )
        return 0
    OUTPUT_PATH.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT_PATH}: {len(rendered.splitlines())} items")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
